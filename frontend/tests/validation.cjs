const assert = require('node:assert/strict');
const { fileError, reviewError } = require('../src/validation.ts');
assert.ok(fileError('empty.png',0,false));
assert.equal(fileError('photo.PNG',100,false),null);
assert.ok(fileError('photo.png',10*1024*1024+1,false));
assert.equal(fileError('photo.png',10*1024*1024,false),null);
assert.ok(fileError('not-image.txt',50,false));
assert.ok(fileError('photo.png',50,true));
assert.equal(fileError('history.XLSX',50,true),null);
assert.equal(reviewError('가상 제품','',''),null);
assert.equal(reviewError('가상 제품','0','mg'),null);
assert.equal(reviewError('가상 제품','0.12345678901234567890','mg'),null);
assert.ok(reviewError('가상 제품','1e309','mg'));
assert.ok(reviewError('가상 제품','-1','mg'));
assert.ok(reviewError('가상 제품','NaN','mg'));
assert.ok(reviewError('가상 제품','1',''));
assert.ok(reviewError('가상 제품','','mg'));
assert.ok(reviewError('   ','1','mg'));
console.log('Input checks passed: empty/oversized/wrong-type files, 0, precise decimals and invalid strength values.');

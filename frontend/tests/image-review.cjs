const assert=require('node:assert/strict');
const {mockExtraction,initialReviewState,reviewReducer,draftIssues,changedFields}=require('../src/imageReviewModel.ts');
const family='00000000-0000-4000-8000-000000000001';
const mocks=kind=>mockExtraction(kind,family,'MEDICINE_BAG','2026-10-19');
const load=kind=>reviewReducer(reviewReducer(initialReviewState(),{type:'start',requestId:1}),{type:'finish',requestId:1,results:mocks(kind)});
for(const kind of ['single','multiple','missing']) {
 const state=load(kind);
 assert.equal(state.phase,'ready');
 assert.ok(state.candidates.every(c=>!c.user_confirmed));
 assert.ok(state.candidates.every(c=>!c.original.record||c.original.record.user_confirmed===false));
}
assert.equal(load('multiple').candidates.length,2);
assert.equal(load('multiple').candidates[1].draft.ingredients.length,2);
assert.equal(load('missing').candidates[0].original.record,null);
assert.ok(draftIssues(load('missing').candidates[0].draft).product);
assert.equal(load('failed').phase,'failed');
assert.equal(load('failed').candidates.length,0);
const mixedResults=[...mocks('single'),...mocks('failed')];
const mixedBefore=structuredClone(mixedResults);
let mixed=reviewReducer(reviewReducer(initialReviewState(),{type:'start',requestId:1}),{type:'finish',requestId:1,results:mixedResults});
assert.equal(mixed.phase,'ready','one failed candidate must not hide a successful candidate');
assert.equal(mixed.candidates.length,2);
assert.deepEqual(mixed.candidates.map(c=>c.original),mixedBefore);
mixed=reviewReducer(mixed,{type:'acknowledge',key:'candidate-1',value:true});
mixed=reviewReducer(mixed,{type:'confirm',key:'candidate-1'});
assert.equal(mixed.candidates[0].user_confirmed,true);
mixed=reviewReducer(mixed,{type:'edit',key:'candidate-2',draft:{...mixed.candidates[1].draft,product:'가상 수동 입력'}});
mixed=reviewReducer(mixed,{type:'acknowledge',key:'candidate-2',value:true});
mixed=reviewReducer(mixed,{type:'confirm',key:'candidate-2'});
assert.equal(mixed.candidates[1].user_confirmed,false,'a failed candidate cannot be repaired into a confirmed record implicitly');
assert.equal(mixed.candidates[1].original.record,null);
assert.deepEqual(mixedResults,mixedBefore,'mixed input must remain immutable');
let state=load('multiple');
state=reviewReducer(state,{type:'confirm',key:'candidate-1'});
assert.equal(state.candidates[0].user_confirmed,false,'must acknowledge original');
state=reviewReducer(state,{type:'acknowledge',key:'candidate-1',value:true});
state=reviewReducer(state,{type:'confirm',key:'candidate-1'});
assert.equal(state.candidates[0].user_confirmed,true);
assert.equal(state.candidates[1].user_confirmed,false,'confirmation is per candidate');
assert.equal(state.candidates[0].original.record.user_confirmed,false,'never mutate upstream record');
state=reviewReducer(state,{type:'edit',key:'candidate-1',draft:{...state.candidates[0].draft,product:'가상 사용자 수정',dose:'0'}});
assert.equal(state.candidates[0].user_confirmed,false);
assert.equal(state.candidates[0].acknowledged,false);
assert.ok(changedFields(state.candidates[0]).includes('product'));
assert.equal(state.candidates[0].original.record.product_name_raw,'가상 추출 제품 1');
assert.deepEqual(draftIssues(state.candidates[0].draft),{});
assert.ok(draftIssues({...state.candidates[0].draft,perDay:'1e309'}).perDay);
assert.ok(draftIssues({...state.candidates[0].draft,dose:'-1'}).dose);
assert.ok(draftIssues({...state.candidates[0].draft,ingredients:[{name:'A',strength:'1',unit:''}]} )['ingredient-0-unit']);
state=reviewReducer(state,{type:'restore',key:'candidate-1'});
assert.deepEqual(changedFields(state.candidates[0]),[]);
state=reviewReducer(state,{type:'defer',key:'candidate-1'});
assert.equal(state.candidates[0].deferred,true);
assert.equal(state.candidates[0].user_confirmed,false);
let pending=reviewReducer(initialReviewState(),{type:'start',requestId:2});
assert.equal(reviewReducer(pending,{type:'start',requestId:3}),pending,'duplicate start ignored');
assert.equal(reviewReducer(pending,{type:'finish',requestId:1,results:mocks('single')}),pending,'stale response ignored');
state=reviewReducer(pending,{type:'reset'});
assert.equal(reviewReducer(state,{type:'finish',requestId:2,results:mocks('single')}),state,'cancelled response ignored');
console.log('Image review checks passed: four cases, independent confirmation, immutable raw values, null/0/false, validation, cancel and stale/duplicate responses.');
